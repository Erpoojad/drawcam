"""TurnSpec -> Fanuc 0i-T style lathe program(s).

Operation order: face, centre/drill, OD rough (G71), OD finish (G70 + G42),
bore (G71/G70 internal), grooves (G75), threads (G76), part-off (G75).
If the profile shrinks again after the largest diameter, OP1 machines the
right-hand side and OP2 (part flipped) machines the rest.
"""
from __future__ import annotations

import math

from ..spec import TurnSpec, ReviewItem
from .gcode import GCode, f
from .shop import rpm


def _split_profile(profile):
    peak = max(range(len(profile)), key=lambda i: (profile[i][1], -i))
    # extend through the flat at max diameter
    end = peak
    while end + 1 < len(profile) and abs(profile[end + 1][1] - profile[peak][1]) < 1e-6:
        end += 1
    rest = profile[end:]
    needs_op2 = any(rest[j][1] < rest[j - 1][1] - 1e-6 for j in range(1, len(rest)))
    if not needs_op2:
        return profile, None
    return profile[:end + 1], rest


def _contour_blocks(g: GCode, prof, chamfer: float, n_start: int, n_end: int, x_exit: float, internal=False):
    """Emit N{start}..N{end} finish contour. prof: [[z, dia], ...] starting at Z0."""
    c = chamfer
    z0, d0 = prof[0]
    sgn = -1 if internal else 1
    g(f"N{n_start}", "G00", f"X{f(d0 - sgn * 2 * c)}")
    g("G01", f"Z{f(z0)}")
    g(f"X{f(d0)}", f"Z{f(z0 - c)}")
    cur_z, cur_d = z0 - c, d0
    for (za, da), (zb, db) in zip(prof, prof[1:]):
        if abs(za - zb) < 1e-6:                                   # vertical step
            step = (db - da) * sgn
            if step > 2 * c + 0.2 and c > 0:
                g(f"X{f(db - sgn * 2 * c)}")
                g(f"X{f(db)}", f"Z{f(zb - c)}")
                cur_z, cur_d = zb - c, db
                continue
        g(f"X{f(db)}", f"Z{f(zb)}")
        cur_z, cur_d = zb, db
    g(f"N{n_end}", "G01", f"X{f(x_exit)}")


def _header(g: GCode, spec: TurnSpec, prog: int, title: str, cfg):
    g("%")
    g(f"O{prog:04d}")
    g.comment(f"{spec.part_name} {title}")
    g.comment(f"MATERIAL {spec.material} STOCK BAR D{spec.stock_dia:g} PART L{spec.part_length:g}")
    g.comment("GENERATED BY DRAWCAM - PROVE OUT IN SINGLE BLOCK WITH OVERRIDES LOW")
    for r in spec.review:
        g.comment(f"CHECK: {r.message}")
    for k, t in cfg["lathe"]["tools"].items():
        g.comment(f"T{t['t']:02d} {t['desc']}")
    g("G21 G40 G99 G18")
    g("G28 U0.")
    g("G28 W0.")


def _tool(g: GCode, t: int):
    g.blank()
    g(f"T{t:02d}{t:02d}")


def _home(g: GCode):
    g("G28 U0.")
    g("G28 W0.")
    g("M01")


def _od_section(g, spec, prof, cfg, m, max_rpm, xs, face=True, chamfer=None):
    T = cfg["lathe"]["tools"]
    c = spec.chamfer if chamfer is None else chamfer
    _tool(g, T["face_rough"]["t"])
    g.comment("FACE + ROUGH OD")
    g(f"G50 S{max_rpm}")
    g(f"G96 S{m['vc_rough']} M03")
    g("G00", f"X{f(xs)}", "Z2.", "M08")
    if face:
        for zf in (0.5, 0.0):
            g("G00", f"Z{f(zf)}")
            g("G01", "X-1.6", f"F{f(m['f_finish'] * 1.5)}")
            g("G00", f"Z{f(zf + 1)}")
            g("G00", f"X{f(xs)}")
    g("G00", "Z2.")
    g("G71", f"U{f(m['doc'])}", "R0.5")
    g("G71", "P100", "Q200", "U0.4", "W0.1", f"F{f(m['f_rough'])}")
    _contour_blocks(g, prof, c, 100, 200, xs)
    _home(g)

    _tool(g, T["finish"]["t"])
    g.comment("FINISH OD - SET NOSE RADIUS AND TIP 3 IN OFFSETS FOR G42")
    g(f"G50 S{max_rpm}")
    g(f"G96 S{m['vc_finish']} M03")
    g("G00", "G42", f"X{f(xs)}", "Z2.", "M08")
    g("G70", "P100", "Q200", f"F{f(m['f_finish'])}")
    g("G00", "G40", f"X{f(xs + 20)}", "Z50.")
    _home(g)


def _prechecks(spec: TurnSpec, cfg, op1):
    """Tooling/geometry problems found while planning; added before the header is written."""
    T = cfg["lathe"]["tools"]
    have = {(r.field, r.message) for r in spec.review}

    def add(field, msg, sev="warn"):
        if (field, msg) not in have:
            spec.review.append(ReviewItem(field, msg, sev))

    if spec.stock_dia > cfg["lathe"]["max_dia"]:
        add("stock", f"stock D{spec.stock_dia} exceeds machine capacity", "block")
    b = spec.bore
    if b and b.dia > 13 and b.dia < T["bore"].get("min_bore", 16):
        add("bore", f"bore Ø{b.dia} is below the boring bar minimum; ream or change tooling", "block")
    for gr in spec.grooves:
        if gr.width < T["groove"]["width"] - 1e-6:
            add("groove", f"groove width {gr.width} narrower than the {T['groove']['width']} mm tool", "block")
    for th in spec.threads:
        if th.z_end < op1[-1][0] - 1e-6:
            add("thread", f"M{th.major_dia:g} lies on the OP2 side and is not auto-programmed", "block")
        elif not any(abs(gr.z + gr.width - th.z_end) < 0.05 for gr in spec.grooves):
            add("thread", f"M{th.major_dia:g}x{th.pitch:g} has no relief groove: thread ends with a 1-pitch pull-out")


def generate_turning(spec: TurnSpec, cfg) -> dict:
    m = cfg["materials"][spec.material]
    L = cfg["lathe"]
    T = L["tools"]
    max_rpm = L["max_rpm"]
    xs = spec.stock_dia + 2.0
    op1, op2 = _split_profile(spec.profile)
    programs = {}
    _prechecks(spec, cfg, op1)

    g = GCode()
    _header(g, spec, L["program_number"], "OP1" if op2 else "", cfg)

    # ---- drill / bore (before OD so the bore runs on a stiff part) ----
    bore = spec.bore
    drill_d = None
    if bore:
        if bore.dia <= 13:
            drill_d = bore.dia
        else:
            drill_d = math.floor(min(bore.dia - 2.0, 25.0) * 2) / 2
        depth = bore.depth + (0.3 * drill_d + 1.0 if bore.through else 0.3 * drill_d)
        _tool(g, T["drill"]["t"])
        g.comment(f"DRILL D{drill_d:g} - LOAD THIS SIZE")
        g(f"G97 S{rpm(m['vc_drill'], drill_d, max_rpm)} M03")
        g("G00", "X0.", "Z5.", "M08")
        g("G74", "R0.5")
        g("G74", f"Z{f(-depth)}", f"Q{int(drill_d * 1000)}", f"F{f(m['f_drill'])}")
        g("G00", "Z50.")
        _home(g)

    _od_section(g, spec, op1, cfg, m, max_rpm, xs)

    if bore and bore.dia > drill_d + 0.05:
        bt = T["bore"]
        _tool(g, bt["t"])
        g.comment(f"BORE D{bore.dia:g} X {bore.depth:g}")
        g(f"G50 S{max_rpm}")
        g(f"G96 S{m['vc_finish']} M03")
        xb = drill_d - 1.0
        g("G00", f"X{f(xb)}", "Z2.", "M08")
        g("G71", "U1.", "R0.5")
        g("G71", "P300", "Q400", "U-0.3", "W0.05", f"F{f(m['f_rough'] * 0.7)}")
        zb = -bore.depth if not bore.through else -(spec.part_length + 0.5)
        _contour_blocks(g, [[0.0, bore.dia], [zb, bore.dia]], min(spec.chamfer, 0.5), 300, 400, xb, internal=True)
        g("G00", "G41", f"X{f(xb)}", "Z2.")
        g("G70", "P300", "Q400", f"F{f(m['f_finish'])}")
        g("G00", "G40", "Z50.")
        _home(g)

    # ---- grooves ----
    gw = T["groove"]["width"]
    for gr in spec.grooves:
        if gr.z < op1[-1][0] - 1e-6:
            continue                                   # belongs to OP2 side
        od = max(p[1] for p in spec.profile if gr.z - 0.01 <= p[0] <= gr.z + gr.width + 0.01) if spec.profile else xs
        _tool(g, T["groove"]["t"])
        g.comment(f"GROOVE W{gr.width:g} TO D{gr.bottom_dia:g} - TOOL REF LEFT EDGE")
        g(f"G97 S{rpm(m['vc_finish'] * 0.6, od, max_rpm)} M03")
        z_right = gr.z + gr.width - gw
        z_right = max(z_right, gr.z)
        g("G00", f"X{f(od + 2)}", f"Z{f(z_right)}", "M08")
        g("G75", "R0.3")
        g("G75", f"X{f(gr.bottom_dia)}", f"Z{f(gr.z)}", f"P{int(1000)}", f"Q{int(gw * 0.8 * 1000)}", "F0.05")
        g("G00", f"X{f(xs + 20)}")
        _home(g)

    # ---- threads ----
    for th in spec.threads:
        if th.z_end < op1[-1][0] - 1e-6:
            continue
        h = 0.6134 * th.pitch
        minor = th.major_dia - 2 * h
        relief = next((gr for gr in spec.grooves if abs(gr.z + gr.width - th.z_end) < 0.05), None)
        z_end = relief.z + relief.width / 2 if relief else th.z_end
        pull = "00" if relief else "10"
        _tool(g, T["thread"]["t"])
        g.comment(f"THREAD M{th.major_dia:g}X{th.pitch:g} - CHECK WITH RING GAUGE")
        s = min(rpm(m["vc_thread"], th.major_dia, max_rpm), int(3000 / th.pitch), 1500)
        g(f"G97 S{s} M03")
        g("G00", f"X{f(th.major_dia + 4)}", f"Z{f(th.z_start + 3 * th.pitch)}", "M08")
        g("G76", f"P02{pull}60", "Q100", "R0.05")
        first = int(max(150, min(400, h * 1000 * 0.35)))
        g("G76", f"X{f(minor)}", f"Z{f(z_end)}", f"P{int(round(h * 1000))}", f"Q{first}", f"F{f(th.pitch)}")
        g("G00", f"X{f(xs + 20)}")
        _home(g)

    # ---- part off ----
    pw = T["part"]["width"]
    allow = 1.0 if op2 else 0.0
    zp = -(spec.part_length + allow + pw)
    x_stop = (spec.bore.dia - 1.0) if (spec.bore and spec.bore.through) else -1.0
    _tool(g, T["part"]["t"])
    g.comment(f"PART OFF{' - LEAVES 1MM FOR OP2 FACING' if op2 else ''} - TOOL REF LEFT EDGE")
    g(f"G97 S{rpm(m['vc_rough'] * 0.5, spec.stock_dia, min(max_rpm, 1500))} M03")
    g("G00", f"X{f(xs)}", f"Z{f(zp)}", "M08")
    g("G75", "R0.5")
    g("G75", f"X{f(x_stop)}", "P3000", "F0.05")
    g("G00", f"X{f(xs + 20)}", "M09")
    g("G28 U0.")
    g("G28 W0.")
    g("M30")
    g("%")
    import re as _re
    g.drop_unused_tool_comments({int(t[:2]) for t in _re.findall(r"^T(\d{4})", g.text(), _re.M)})
    programs["OP1"] = g.text()

    # ---- OP2: flip, face to length, turn remaining side ----
    if op2:
        Lp = spec.part_length
        prof2 = [[round(-Lp - z, 4), d] for z, d in reversed(op2)]
        g2 = GCode()
        _header(g2, spec, L["program_number"] + 1, "OP2 - PART FLIPPED, GRIP ON OP1 DIAMETER", cfg)
        g2.comment(f"PARTED LENGTH IS {Lp + 1:g}: TOUCH THE PARTED FACE AND SET IT AS Z+1.0 SO Z0 = FINISHED LENGTH {Lp:g}")
        _od_section(g2, spec, prof2, cfg, m, max_rpm, xs, face=True)
        # grooves/threads living on the OP2 side
        for th in spec.threads:
            if th.z_end >= op1[-1][0] - 1e-6:
                continue
            g2.comment(f"THREAD M{th.major_dia:g} ON OP2 SIDE - ADD MANUALLY OR EXTEND GENERATOR")
        g2("M09")
        g2("G28 U0.")
        g2("G28 W0.")
        g2("M30")
        g2("%")
        g2.drop_unused_tool_comments({int(t[:2]) for t in _re.findall(r"^T(\d{4})", g2.text(), _re.M)})
        programs["OP2"] = g2.text()
    return programs
